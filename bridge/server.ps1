# Studio bridge
#
# A tiny local web server (Windows PowerShell 5.1, nothing to install) that:
#   * serves the studio at http://localhost:<port>/
#   * relays live-link packets (VMC/OSC) from the browser to inZOI over UDP
#   * saves exports into Documents\Zoi Motion Studio
#   * finds your inZOI install to load the body-tracking Zoi
# It only listens on this PC and only accepts requests from the studio page itself.

param(
  [int]$Port = 47820,
  [switch]$NoBrowser,
  [int]$AiPort = 0   # text-to-motion AI server; 0 = this helper's port + 100
)

$ErrorActionPreference = 'Stop'
$Version = '1.1.0'
$StudioRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\studio')).Path
$DataDir = Join-Path ([Environment]::GetFolderPath('MyDocuments')) 'Zoi Motion Studio'
New-Item -ItemType Directory -Force -Path $DataDir | Out-Null

$Mime = @{
  '.html' = 'text/html; charset=utf-8'; '.js' = 'text/javascript; charset=utf-8'; '.mjs' = 'text/javascript; charset=utf-8'
  '.css' = 'text/css; charset=utf-8'; '.json' = 'application/json; charset=utf-8'; '.svg' = 'image/svg+xml'
  '.png' = 'image/png'; '.jpg' = 'image/jpeg'; '.ico' = 'image/x-icon'; '.wasm' = 'application/wasm'
  '.glb' = 'model/gltf-binary'; '.fbx' = 'application/octet-stream'; '.bvh' = 'text/plain; charset=utf-8'; '.txt' = 'text/plain; charset=utf-8'
}

function Find-Inzoi {
  $libs = New-Object System.Collections.Generic.List[string]
  try {
    $steam = (Get-ItemProperty 'HKCU:\Software\Valve\Steam' -ErrorAction Stop).SteamPath
    if ($steam) {
      $libs.Add($steam)
      $vdf = Join-Path $steam 'steamapps\libraryfolders.vdf'
      if (Test-Path $vdf) {
        foreach ($m in [regex]::Matches((Get-Content $vdf -Raw), '"path"\s+"([^"]+)"')) { $libs.Add($m.Groups[1].Value.Replace('\\', '\')) }
      }
    }
  } catch { }
  $libs.Add('C:\Program Files (x86)\Steam')
  foreach ($l in $libs) {
    $p = Join-Path $l 'steamapps\common\inZOI'
    if (Test-Path (Join-Path $p 'inZOI.exe')) { return (Resolve-Path $p).Path }
  }
  return $null
}

$RuntimeSrc = (Resolve-Path (Join-Path $PSScriptRoot '..\runtime\ZoiAnimFramework')).Path
$ModsInGame = Join-Path ([Environment]::GetFolderPath('MyDocuments')) 'inZOI\Mods\InGame'
$RuntimeDst = Join-Path $ModsInGame 'ZoiAnimFramework'

$GamePath = Find-Inzoi
$VrmPath = if ($GamePath) { Join-Path $GamePath 'Guides\MotionCapture\BodyTrackingVrm.vrm' } else { $null }
$HasVrm = [bool]($VrmPath -and (Test-Path $VrmPath))

$Udp = New-Object System.Net.Sockets.UdpClient
$Udp.Client.SendBufferSize = 1048576

function Send-Bytes($ctx, [byte[]]$bytes, [string]$type, [int]$status = 200) {
  $res = $ctx.Response
  $res.StatusCode = $status
  $res.ContentType = $type
  $res.Headers['Cache-Control'] = 'no-cache'
  $res.Headers['X-Content-Type-Options'] = 'nosniff'
  $res.ContentLength64 = $bytes.Length
  $res.OutputStream.Write($bytes, 0, $bytes.Length)
}

function Send-Json($ctx, $obj, [int]$status = 200) {
  $json = $obj | ConvertTo-Json -Depth 6 -Compress
  Send-Bytes $ctx ([Text.Encoding]::UTF8.GetBytes($json)) 'application/json; charset=utf-8' $status
}

function Send-Text($ctx, [string]$text, [int]$status) {
  Send-Bytes $ctx ([Text.Encoding]::UTF8.GetBytes($text)) 'text/plain; charset=utf-8' $status
}

function Read-Body($req) {
  $ms = New-Object System.IO.MemoryStream
  $req.InputStream.CopyTo($ms)
  return ,$ms.ToArray()
}

# Requests that change anything must come from the studio page itself (blocks other websites).
# The in-game panel (coui://) may only reach the read-only /api/zaf/* endpoints.
function Test-Origin($req) {
  $origin = $req.Headers['Origin']
  if (-not $origin) { return $true }
  if ($origin -like 'coui://*' -and $req.Url.AbsolutePath -like '/api/zaf/*') { return $true }
  return ($origin -eq "http://localhost:$Port" -or $origin -eq "http://127.0.0.1:$Port")
}

function Get-InstalledPacks {
  $dir = Join-Path $RuntimeDst 'ui\zaf\packs'
  if (-not (Test-Path $dir)) { return @() }
  return @(Get-ChildItem $dir -Filter '*.json' | ForEach-Object { $_.BaseName })
}

# Regenerates ui/zaf/packs/installed.js from the pack manifests in that folder.
function Write-PackIndex {
  $dir = Join-Path $RuntimeDst 'ui\zaf\packs'
  New-Item -ItemType Directory -Force -Path $dir | Out-Null
  $sb = New-Object System.Text.StringBuilder
  [void]$sb.AppendLine('// Generated by Studio. Packs installed with "Install to inZOI".')
  [void]$sb.AppendLine('window.ZAF_PACKS = window.ZAF_PACKS || [];')
  foreach ($f in (Get-ChildItem $dir -Filter '*.json' | Sort-Object Name)) {
    $json = [IO.File]::ReadAllText($f.FullName, [Text.Encoding]::UTF8)
    [void]$sb.AppendLine('window.ZAF_PACKS.push(' + $json.Trim() + ');')
  }
  [IO.File]::WriteAllText((Join-Path $dir 'installed.js'), $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
}

function Install-Runtime {
  New-Item -ItemType Directory -Force -Path $RuntimeDst | Out-Null
  foreach ($f in (Get-ChildItem $RuntimeSrc -Recurse -File)) {
    $rel = $f.FullName.Substring($RuntimeSrc.Length).TrimStart('\')
    if ($rel -like 'ui\zaf\packs\*') { continue }   # keep the player's installed packs
    $target = Join-Path $RuntimeDst $rel
    New-Item -ItemType Directory -Force -Path (Split-Path $target) | Out-Null
    Copy-Item $f.FullName $target -Force
  }
  Write-PackIndex
}

# Permanent mods through the inZOI ModKit (tools\modkit\build_mod.ps1). A build takes a few minutes, so it
# runs as its own hidden process and reports progress in <folder>\modkit_build\status.json.
# Builds without tools\modkit (e.g. an install that does not ship it) answer 503 instead of failing at startup.
$ModKitBuilder = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\tools\modkit\build_mod.ps1'))
$ModKitBuild = $null

function Get-ModKitStatusPath([string]$dir) { return Join-Path $dir 'modkit_build\status.json' }

function Start-ModKitBuild([string]$dir, [string]$extra) {
  $status = Get-ModKitStatusPath $dir
  if (Test-Path $status) { Remove-Item $status -Force }
  $argList = "-NoProfile -ExecutionPolicy Bypass -File `"$ModKitBuilder`" -StatusFile `"$status`" $extra"
  $script:ModKitBuild = Start-Process powershell.exe -ArgumentList $argList -WindowStyle Hidden -PassThru
}

function Resolve-DataPath([string]$rel) {
  if (-not $rel) { return $DataDir }
  $rel = $rel -replace '/', '\'
  if ($rel -match '(^|\\)\.\.(\\|$)' -or [IO.Path]::IsPathRooted($rel) -or $rel -match '[:*?"<>|]') { throw 'Invalid path' }
  $full = [IO.Path]::GetFullPath((Join-Path $DataDir $rel))
  if (-not $full.StartsWith($DataDir, [StringComparison]::OrdinalIgnoreCase)) { throw 'Invalid path' }
  return $full
}

function Handle-Vmc($ctx) {
  $q = $ctx.Request.QueryString
  $h = if ($q['host']) { $q['host'] } else { '127.0.0.1' }
  $p = if ($q['port']) { [int]$q['port'] } else { 39539 }
  $body = Read-Body $ctx.Request
  $o = 0; $n = 0
  while ($o + 4 -le $body.Length) {
    $len = ([int]$body[$o] -shl 24) -bor ([int]$body[$o + 1] -shl 16) -bor ([int]$body[$o + 2] -shl 8) -bor [int]$body[$o + 3]
    $o += 4
    if ($len -le 0 -or $o + $len -gt $body.Length) { break }
    $packet = New-Object byte[] $len
    [Array]::Copy($body, $o, $packet, 0, $len)
    [void]$Udp.Send($packet, $len, $h, $p)
    $o += $len; $n++
  }
  Send-Json $ctx @{ ok = $true; packets = $n }
}

# ------------------------------------------------------------------ text-to-motion AI (ai\server.py)
# ai\setup_ai.ps1 installs it (the installer runs it; the studio can run it again). The helper starts
# the AI server the first time the studio asks for it; the server stops by itself when the helper exits.
$AiDir = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\ai'))
$AiServer = $null
$AiSetup = $null

function Test-AiInstalled {
  return (Test-Path (Join-Path $AiDir 'runtime\ready.json')) -and (Test-Path (Join-Path $AiDir 'runtime\venv\Scripts\pythonw.exe'))
}
function Get-AiSetupStatus {
  $f = Join-Path $AiDir 'runtime\setup_status.json'
  if (Test-Path $f) { try { return Get-Content $f -Raw | ConvertFrom-Json } catch { } }
  return $null
}
function Test-AiSetupRunning { return [bool]($script:AiSetup -and -not $script:AiSetup.HasExited) }
function Start-AiServer {
  if ($script:AiServer -and -not $script:AiServer.HasExited) { return }
  $py = Join-Path $AiDir 'runtime\venv\Scripts\pythonw.exe'
  $script:AiServer = Start-Process $py -ArgumentList "`"$(Join-Path $AiDir 'server.py')`" --port $AiPort --parent $PID" -WorkingDirectory $AiDir -WindowStyle Hidden -PassThru
}
function Start-AiSetup {
  if (Test-AiSetupRunning) { return }
  $script:AiSetup = Start-Process powershell.exe -ArgumentList "-NoProfile -ExecutionPolicy Bypass -File `"$(Join-Path $AiDir 'setup_ai.ps1')`"" -WindowStyle Hidden -PassThru
}
# What the studio sees while the AI server is not answering: installing, starting, or not installed.
function Send-AiOffline($ctx, [bool]$isGenerate) {
  if (-not (Test-Path (Join-Path $AiDir 'setup_ai.ps1'))) {
    Send-Json $ctx @{ ok = $true; ready = $false; state = 'unavailable'; installed = $false; message = 'This copy of Studio does not include the AI.' } $(if ($isGenerate) { 503 } else { 200 }); return
  }
  $setup = Get-AiSetupStatus
  if ((Test-AiSetupRunning) -or ($setup -and $setup.state -eq 'running' -and -not (Test-AiInstalled))) {
    Send-Json $ctx @{ ok = $true; ready = $false; state = 'installing'; installed = $false; percent = $(if ($setup) { $setup.percent } else { 0 }); message = $(if ($setup) { $setup.message } else { 'Setting up the AI' }) } $(if ($isGenerate) { 503 } else { 200 }); return
  }
  if (Test-AiInstalled) {
    Start-AiServer
    Send-Json $ctx @{ ok = $true; ready = $false; state = 'starting'; installed = $true; message = 'Starting the AI (the first start can take up to a minute)' } $(if ($isGenerate) { 503 } else { 200 }); return
  }
  $msg = if ($setup -and $setup.state -eq 'error') { $setup.message } else { 'The AI model is not downloaded yet.' }
  Send-Json $ctx @{ ok = $true; ready = $false; state = 'missing'; installed = $false; message = $msg } $(if ($isGenerate) { 503 } else { 200 })
}

function Handle-AiProxy($ctx) {
  $req = $ctx.Request
  if (-not ($AiServer -and -not $AiServer.HasExited)) { Send-AiOffline $ctx ($req.HttpMethod -eq 'POST'); return }
  try {
    $url = "http://127.0.0.1:$AiPort" + $req.Url.PathAndQuery
    $wr = [System.Net.HttpWebRequest]::Create($url)
    $wr.Method = $req.HttpMethod
    $wr.Timeout = 600000
    $wr.ReadWriteTimeout = 600000
    if ($req.HttpMethod -eq 'POST') {
      $body = Read-Body $req
      $wr.ContentType = 'application/json'
      $wr.ContentLength = $body.Length
      $s = $wr.GetRequestStream(); $s.Write($body, 0, $body.Length); $s.Close()
    }
    $resp = $wr.GetResponse()
    $ms = New-Object System.IO.MemoryStream
    $resp.GetResponseStream().CopyTo($ms)
    Send-Bytes $ctx $ms.ToArray() $resp.ContentType ([int]$resp.StatusCode)
    $resp.Close()
  } catch [System.Net.WebException] {
    if ($_.Exception.Response) {
      $r = $_.Exception.Response
      $ms = New-Object System.IO.MemoryStream
      $r.GetResponseStream().CopyTo($ms)
      Send-Bytes $ctx $ms.ToArray() 'application/json' ([int]$r.StatusCode)
    } else {
      # Started but not listening yet (Python is still loading).
      Send-Json $ctx @{ ok = $true; ready = $false; state = 'starting'; installed = $true; message = 'Starting the AI (the first start can take up to a minute)' } $(if ($req.HttpMethod -eq 'POST') { 503 } else { 200 })
    }
  }
}

function Handle-Static($ctx) {
  $path = [Uri]::UnescapeDataString($ctx.Request.Url.AbsolutePath)
  if ($path -eq '/' -or $path -eq '') { $path = '/index.html' }
  $full = [IO.Path]::GetFullPath((Join-Path $StudioRoot ($path.TrimStart('/') -replace '/', '\')))
  if (-not $full.StartsWith($StudioRoot, [StringComparison]::OrdinalIgnoreCase) -or -not (Test-Path $full -PathType Leaf)) {
    Send-Text $ctx 'Not found' 404
    return
  }
  $ext = [IO.Path]::GetExtension($full).ToLower()
  $type = if ($Mime.ContainsKey($ext)) { $Mime[$ext] } else { 'application/octet-stream' }
  Send-Bytes $ctx ([IO.File]::ReadAllBytes($full)) $type
}

function Handle($ctx) {
  $req = $ctx.Request
  $path = $req.Url.AbsolutePath
  $method = $req.HttpMethod
  if ($method -ne 'GET' -and -not (Test-Origin $req)) { Send-Text $ctx 'Forbidden' 403; return }
  switch -Regex ($path) {
    '^/api/status$' {
      Send-Json $ctx @{
        ok = $true; version = $Version; port = $Port; dataDir = $DataDir
        game = @{ path = $GamePath; vrm = $HasVrm }
      }
      return
    }
    '^/api/vmc$' { if ($method -eq 'POST') { Handle-Vmc $ctx } else { Send-Text $ctx 'POST only' 405 }; return }
    '^/api/game/vrm$' {
      if ($HasVrm) { Send-Bytes $ctx ([IO.File]::ReadAllBytes($VrmPath)) 'model/gltf-binary' } else { Send-Text $ctx 'inZOI body-tracking file not found' 404 }
      return
    }
    '^/api/save$' {
      if ($method -ne 'POST') { Send-Text $ctx 'POST only' 405; return }
      $full = Resolve-DataPath $req.QueryString['path']
      New-Item -ItemType Directory -Force -Path (Split-Path $full) | Out-Null
      [IO.File]::WriteAllBytes($full, (Read-Body $req))
      Send-Json $ctx @{ ok = $true; path = $full }
      return
    }
    '^/api/reveal$' {
      $full = Resolve-DataPath $req.QueryString['path']
      New-Item -ItemType Directory -Force -Path $full | Out-Null
      Start-Process explorer.exe -ArgumentList "`"$full`""
      Send-Json $ctx @{ ok = $true }
      return
    }
    '^/api/zaf/status$' {
      $ctx.Response.Headers['Access-Control-Allow-Origin'] = '*'
      Send-Json $ctx @{ ok = $true; version = $Version; studio = "http://localhost:$Port/" }
      return
    }
    '^/api/runtime/status$' {
      Send-Json $ctx @{ installed = (Test-Path (Join-Path $RuntimeDst 'mod_manifest.json')); path = $RuntimeDst; packs = @(Get-InstalledPacks) }
      return
    }
    '^/api/runtime/install$' {
      if ($method -ne 'POST') { Send-Text $ctx 'POST only' 405; return }
      Install-Runtime
      Send-Json $ctx @{ ok = $true; path = $RuntimeDst }
      return
    }
    '^/api/runtime/pack$' {
      if ($method -ne 'POST') { Send-Text $ctx 'POST only' 405; return }
      $body = [Text.Encoding]::UTF8.GetString((Read-Body $req))
      $pack = $body | ConvertFrom-Json
      $id = [string]$pack.id
      if (-not $id -or $id -notmatch '^[A-Za-z0-9_.-]+$') { Send-Text $ctx 'Pack id must use letters, numbers, dot, dash or underscore' 400; return }
      if (-not (Test-Path (Join-Path $RuntimeDst 'mod_manifest.json'))) { Install-Runtime }
      $dir = Join-Path $RuntimeDst 'ui\zaf\packs'
      New-Item -ItemType Directory -Force -Path $dir | Out-Null
      [IO.File]::WriteAllText((Join-Path $dir ($id + '.json')), $body, (New-Object Text.UTF8Encoding($false)))
      Write-PackIndex
      Send-Json $ctx @{ ok = $true; path = $RuntimeDst; packs = @(Get-InstalledPacks) }
      return
    }
    '^/api/modkit/(build|skeleton)$' {
      if ($method -ne 'POST') { Send-Text $ctx 'POST only' 405; return }
      if (-not (Test-Path $ModKitBuilder)) { Send-Json $ctx @{ ok = $false; message = 'The ModKit tools are not installed (tools\modkit is missing).' } 503; return }
      if ($ModKitBuild -and -not $ModKitBuild.HasExited) { Send-Json $ctx @{ ok = $false; message = 'A ModKit build is already running.' } 409; return }
      if ($Matches[1] -eq 'build') {
        $dir = Resolve-DataPath $req.QueryString['path']
        if (-not (Test-Path (Join-Path $dir 'zaf_pack.json'))) { Send-Text $ctx 'No zaf_pack.json in that folder' 400; return }
        Start-ModKitBuild $dir "-Pack `"$dir`""
      } else {
        $dir = Join-Path $DataDir 'Characters'
        Start-ModKitBuild $dir ("-ExportZoiSkeleton -SkeletonOut `"" + (Join-Path $dir 'Zoi body (inZOI ModKit).fbx') + "`"")
      }
      Send-Json $ctx @{ ok = $true }
      return
    }
    '^/api/modkit/status$' {
      $rel = if ($req.QueryString['path']) { $req.QueryString['path'] } else { 'Characters' }
      $status = Get-ModKitStatusPath (Resolve-DataPath $rel)
      $running = [bool]($ModKitBuild -and -not $ModKitBuild.HasExited)
      if (Test-Path $status) {
        $s = [IO.File]::ReadAllText($status) | ConvertFrom-Json
        if ($s.state -eq 'running' -and -not $running) { $s.state = 'error'; $s.message = 'The ModKit build stopped unexpectedly. The logs are in the modkit_build folder.' }
        Send-Json $ctx $s
      } else {
        Send-Json $ctx @{ state = $(if ($running) { 'running' } else { 'idle' }) }
      }
      return
    }
    '^/api/ai/setup$' {
      if ($method -ne 'POST') { Send-Text $ctx 'POST only' 405; return }
      if (-not (Test-Path (Join-Path $AiDir 'setup_ai.ps1'))) { Send-Json $ctx @{ ok = $false; message = 'This copy of Studio does not include the AI.' } 404; return }
      if (-not (Test-AiInstalled)) { Start-AiSetup }
      Send-Json $ctx @{ ok = $true; installed = (Test-AiInstalled) }
      return
    }
    '^/api/ai/' { Handle-AiProxy $ctx; return }
    '^/api/' { Send-Text $ctx 'Unknown endpoint' 404; return }
    default { Handle-Static $ctx }
  }
}

# Start listening (try the next ports if this one is busy).
$listener = $null
for ($try = 0; $try -lt 10; $try++) {
  $l = New-Object System.Net.HttpListener
  $l.Prefixes.Add("http://localhost:$Port/")
  $l.Prefixes.Add("http://127.0.0.1:$Port/")
  try { $l.Start(); $listener = $l; break } catch { $Port++ }
}
if (-not $listener) { Write-Host 'Could not open a local port for the studio.' -ForegroundColor Red; Read-Host 'Press Enter to close'; exit 1 }

$url = "http://localhost:$Port/"
if ($AiPort -le 0) { $AiPort = $Port + 100 }
Write-Host ''
Write-Host '  Studio' -ForegroundColor Magenta
Write-Host "  Running at $url" -ForegroundColor Cyan
Write-Host "  Exports and projects: $DataDir"
if ($GamePath) { Write-Host "  inZOI found: $GamePath" -ForegroundColor Green } else { Write-Host '  inZOI not found (live link still works; load the body file by hand).' -ForegroundColor Yellow }
Write-Host ''
Write-Host '  Keep this window open while you use the studio. Close it to stop.' -ForegroundColor DarkGray
Write-Host ''
if (-not $NoBrowser) { Start-Process $url }

try {
  while ($listener.IsListening) {
    $ctx = $listener.GetContext()
    try { Handle $ctx }
    catch {
      try { Send-Text $ctx ($_.Exception.Message) 500 } catch { }
    }
    finally {
      try { $ctx.Response.Close() } catch { }
    }
  }
} finally {
  $listener.Stop()
  $Udp.Close()
}
